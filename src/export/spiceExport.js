/**
 * Standard SPICE3 / LTspice Compatible Netlist (.cir) Generator.
 * Converts any KIRCHHOFF compiled netlist into a clean, runnable SPICE deck.
 */

import { formatSpiceValue } from '../engine/units.js';
import { getDiodePhysics } from '../engine/components.js';

function nName(node) {
  return node === 0 ? '0' : `N${node}`;
}

/**
 * Generate a standards-compliant SPICE .cir netlist string.
 * @param {object} schematic
 * @param {object} netlist - CompiledNetlist
 * @param {object} [simConfig]
 * @returns {string}
 */
export function exportSpiceNetlist(schematic, netlist, simConfig = {}) {
  const lines = [];
  const title = schematic.name || 'Wirebench Circuit';
  lines.push(`* ${title}`);
  lines.push(`* Generated by Wirebench Electronics Studio`);
  lines.push(`* Nodes: ${netlist.numNodes - 1} active + GND (0)`);
  lines.push('');

  const usedModels = new Map();

  for (const cc of netlist.components) {
    const p = cc.params;
    const n = cc.pinNodes;
    const ref = (cc.designator || cc.id).replace(/\s+/g, '_');

    switch (cc.type) {
      case 'ground':
      case 'probe':
        if (cc.type === 'probe') {
          lines.push(`* Probe ${ref} (${p.label || 'CH' + p.channel}) -> ${nName(n.p)}`);
        }
        break;

      case 'resistor':
        lines.push(`${ref.startsWith('R') ? ref : 'R_' + ref} ${nName(n.a)} ${nName(n.b)} ${formatSpiceValue(p.resistance)}`);
        break;

      case 'potentiometer': {
        const w = Math.min(0.999, Math.max(0.001, Number(p.wiper) ?? 0.5));
        const r1 = p.resistance * w;
        const r2 = p.resistance * (1 - w);
        lines.push(`* Potentiometer ${ref} (${formatSpiceValue(p.resistance)}, wiper=${Math.round(w * 100)}%)`);
        lines.push(`R_${ref}_A ${nName(n.a)} ${nName(n.wiper)} ${formatSpiceValue(r1)}`);
        lines.push(`R_${ref}_B ${nName(n.wiper)} ${nName(n.b)} ${formatSpiceValue(r2)}`);
        break;
      }

      case 'capacitor': {
        const ic = Math.abs(Number(p.initialVoltage) || 0) > 1e-9 ? ` IC=${p.initialVoltage}` : '';
        lines.push(`${ref.startsWith('C') ? ref : 'C_' + ref} ${nName(n.a)} ${nName(n.b)} ${formatSpiceValue(p.capacitance)}${ic}`);
        break;
      }

      case 'inductor':
        lines.push(`${ref.startsWith('L') ? ref : 'L_' + ref} ${nName(n.a)} ${nName(n.b)} ${formatSpiceValue(p.inductance)} Rser=${formatSpiceValue(p.seriesResistance || 0.5)}`);
        break;

      case 'switch':
      case 'pushbutton': {
        const rVal = p.closed ? formatSpiceValue(p.rOn || 0.05) : '100G';
        lines.push(`R_${ref} ${nName(n.a)} ${nName(n.b)} ${rVal} ; ${p.closed ? 'CLOSED' : 'OPEN'}`);
        break;
      }

      case 'current_source':
        // SPICE I n+ n- flows n+ -> n- inside source; our 'in' -> 'out' flows in -> out
        lines.push(`${ref.startsWith('I') ? ref : 'I_' + ref} ${nName(n.in)} ${nName(n.out)} DC ${formatSpiceValue(p.current)}`);
        break;

      case 'voltage_source': {
        const name = ref.startsWith('V') ? ref : 'V_' + ref;
        const ac = Number(p.acMag) > 0 ? ` AC ${p.acMag}` : '';
        const wf = p.waveform || 'dc';
        if (wf === 'dc') {
          lines.push(`${name} ${nName(n.pos)} ${nName(n.neg)} DC ${p.dc ?? 0}${ac}`);
        } else if (wf === 'sine') {
          lines.push(`${name} ${nName(n.pos)} ${nName(n.neg)} SIN(${p.dc ?? 0} ${p.amplitude ?? 5} ${formatSpiceValue(p.frequency ?? 1000)} 0 0 ${p.phase ?? 0})${ac}`);
        } else if (wf === 'square' || wf === 'pulse') {
          const per = 1 / Math.max(1e-6, p.frequency || 1000);
          const tr = per * 0.008;
          const duty = p.duty ?? 0.5;
          const pw = Math.max(tr, per * duty - tr);
          const low = wf === 'pulse' ? (p.dc ?? 0) : (p.dc ?? 0) - (p.amplitude ?? 5);
          const high = (p.dc ?? 0) + (p.amplitude ?? 5);
          lines.push(`${name} ${nName(n.pos)} ${nName(n.neg)} PULSE(${low} ${high} 0 ${formatSpiceValue(tr)} ${formatSpiceValue(tr)} ${formatSpiceValue(pw)} ${formatSpiceValue(per)})${ac}`);
        } else if (wf === 'triangle') {
          const per = 1 / Math.max(1e-6, p.frequency || 1000);
          const low = (p.dc ?? 0) - (p.amplitude ?? 5);
          const high = (p.dc ?? 0) + (p.amplitude ?? 5);
          lines.push(`${name} ${nName(n.pos)} ${nName(n.neg)} PULSE(${low} ${high} 0 ${formatSpiceValue(per / 2)} ${formatSpiceValue(per / 2)} 1n ${formatSpiceValue(per)})${ac}`);
        }
        break;
      }

      case 'diode':
      case 'led': {
        const phys = getDiodePhysics(cc);
        const mName = cc.type === 'led'
          ? `LED_${(p.color || 'green').toUpperCase()}`
          : p.model === 'zener'
            ? `DZ_${String(p.vBreakdown || 5.1).replace('.', 'V')}`
            : p.model === 'schottky'
              ? 'D_1N5819'
              : 'D_1N4148';
        if (!usedModels.has(mName)) {
          const bvPart = phys.isZener ? ` BV=${phys.bv} IBV=1m` : '';
          usedModels.set(mName, `.model ${mName} D(IS=${phys.is.toExponential(2)} N=${phys.n}${bvPart})`);
        }
        lines.push(`${ref.startsWith('D') ? ref : 'D_' + ref} ${nName(n.anode)} ${nName(n.cathode)} ${mName}`);
        break;
      }

      case 'npn':
      case 'pnp': {
        const isPnp = cc.type === 'pnp';
        const mName = isPnp ? `Q_PNP_${Math.round(p.betaF || 120)}` : `Q_NPN_${Math.round(p.betaF || 120)}`;
        if (!usedModels.has(mName)) {
          usedModels.set(
            mName,
            `.model ${mName} ${isPnp ? 'PNP' : 'NPN'}(IS=${(p.is || 1e-14).toExponential(1)} BF=${p.betaF || 120} BR=${p.betaR || 2} CJE=35p CJC=15p)`
          );
        }
        lines.push(`${ref.startsWith('Q') ? ref : 'Q_' + ref} ${nName(n.c)} ${nName(n.b)} ${nName(n.e)} ${mName}`);
        break;
      }

      case 'opamp': {
        const g = p.gain || 1e5;
        const vPos = p.vPos ?? 12;
        const vNeg = p.vNeg ?? -12;
        const vMid = 0.5 * (vPos + vNeg);
        const vSpan = 0.5 * (vPos - vNeg);
        const intNode = `${ref}_INT`;
        lines.push(`* Behavioral rail-limited Op-Amp ${ref} (Aol=${g}, rails=[${vNeg}V, +${vPos}V])`);
        lines.push(`R_${ref}_IN ${nName(n.inPos)} ${nName(n.inNeg)} 10Meg`);
        lines.push(`B_${ref} ${intNode} 0 V=${vMid}+${vSpan}*tanh(${g}*(V(${nName(n.inPos)})-V(${nName(n.inNeg)}))/${vSpan})`);
        lines.push(`R_${ref}_OUT ${intNode} ${nName(n.out)} ${formatSpiceValue(p.rOut || 50)}`);
        break;
      }

      case 'nmos':
      case 'pmos': {
        const isP = cc.type === 'pmos';
        const mName = `${isP ? 'PMOS' : 'NMOS'}_${String(p.vth || 1.5).replace('.', 'V')}`;
        if (!usedModels.has(mName)) {
          const vto = isP ? -(p.vth || 1.5) : p.vth || 1.5;
          usedModels.set(
            mName,
            `.model ${mName} ${isP ? 'PMOS' : 'NMOS'}(LEVEL=1 VTO=${vto} KP=${p.kp || 0.08} LAMBDA=${p.lambda ?? 0.02})`
          );
        }
        lines.push(`${ref.startsWith('M') ? ref : 'M_' + ref} ${nName(n.d)} ${nName(n.g)} ${nName(n.s)} ${nName(n.s)} ${mName}`);
        break;
      }

      case 'spdt': {
        const pos = Number(p.position) === 1 ? 1 : 0;
        const rOn = formatSpiceValue(p.rOn || 0.05);
        lines.push(`R_${ref}_A ${nName(n.com)} ${nName(n.a)} ${pos === 0 ? rOn : '100G'}`);
        lines.push(`R_${ref}_B ${nName(n.com)} ${nName(n.b)} ${pos === 1 ? rOn : '100G'}`);
        break;
      }

      case 'voltmeter':
        lines.push(`R_${ref}_VM ${nName(n.pos)} ${nName(n.neg)} 10Meg ; Voltmeter`);
        break;

      case 'ammeter':
        lines.push(`R_${ref}_AM ${nName(n.pos)} ${nName(n.neg)} 10m ; Ammeter Shunt`);
        break;

      case 'logic_in':
        lines.push(`V_${ref} ${nName(n.out)} 0 DC ${p.state ? p.vHigh || 5 : 0} ; Logic ${p.state ? '1' : '0'}`);
        break;

      case 'transformer': {
        const ratio = p.ratio || 0.5;
        lines.push(`* Ideal Transformer ${ref} (ratio Ns/Np = ${ratio})`);
        lines.push(`E_${ref} ${nName(n.s1)} ${nName(n.s2)} ${nName(n.p1)} ${nName(n.p2)} ${ratio}`);
        break;
      }

      case 'gate_and':
      case 'gate_or':
      case 'gate_not':
      case 'gate_nand':
      case 'gate_xor': {
        const kind = cc.type.replace('gate_', '').toUpperCase();
        const pins = cc.type === 'gate_not' ? `${nName(n.a)} ${nName(n.out)}` : `${nName(n.a)} ${nName(n.b)} ${nName(n.out)}`;
        lines.push(`* CMOS ${kind} Gate ${ref} (VDD=${p.vdd || 5}V): ${pins}`);
        break;
      }
    }
  }

  if (usedModels.size > 0) {
    lines.push('');
    lines.push('* Device Models');
    for (const modelDef of usedModels.values()) {
      lines.push(modelDef);
    }
  }

  lines.push('');
  lines.push('* Simulation Directives');
  const dt = simConfig.dt || 2e-5;
  const tStop = (simConfig.scopeTimeDiv || 0.001) * 10;
  lines.push(`.tran ${formatSpiceValue(dt)} ${formatSpiceValue(tStop)}${simConfig.initialMode === 'zero' ? ' uic' : ''}`);
  if (simConfig.bodeStart || simConfig.bodeStop) {
    lines.push(`.ac dec 40 ${simConfig.bodeStart || 10} ${simConfig.bodeStop || 100000}`);
  }
  lines.push('.end');
  return lines.join('\n');
}
